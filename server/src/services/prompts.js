export const buildTaskGeneratorPrompt = ({ count, city, exclude = [] }) => {
  const cityLine = city ? `Город игрока: ${city}. Учитывай типичную для него городскую среду.` : "Город не задан — задания должны работать в любом городе.";
  const excludeLine = exclude.length
    ? `Не повторяй эти задания: ${exclude.slice(0, 60).join("; ")}.`
    : "";
  return `Сгенерируй ${count} заданий. ${cityLine} ${excludeLine}
Распределение сложности: примерно 25% — 1, 30% — 2, 25% — 3, 15% — 4, 5% — 5.
Категории должны быть перемешаны.`;
};

