const VOWELS = 'аоуыиэеёюя';
const SOFTENERS = 'еёиюяь';
const DEVOICE = 'бвгджз';

export const ITEMS = raw.flatMap((words, s) => words.map((w, cell) => {
  const marked = w.replace(/-/g, '');
  const up = [...marked].findIndex((ch) => ch !== ch.toLowerCase());
  const syl = w.toLowerCase().split('-');
  const word = syl.join('');
  const stress = up >= 0 ? up : [...word].findIndex((ch) => VOWELS.includes(ch)); // индекс ударной гласной
  const f = word[0], f2 = word[1];
  const L = word[word.length - 1];
  // безударная «о» звучит как [а]: «оса» — [аса], «облако» на конце — [ъ]
  const reduced = (i) => word[i] === 'о' && i !== stress;
  return {
    word, syl, stress,
    img: `assets/items/s${s + 1}_${cell}.webp`,
    // первый звук: я/ё/ю/е в начале дают [й], безударная «о» — [а]: такие слова в игру не берём
    first: 'яёюей'.includes(f) || reduced(0) ? null : f.toUpperCase(),
    letter: f.toUpperCase(), // первая буква (для азбуки — буква, а не звук)
    // последний звук: без ь, без йотированных и без оглушения на конце (хлеб → [п])
    last: ('ьйяеёю' + DEVOICE).includes(L) || reduced(word.length - 1) ? null : L.toUpperCase(),
    // твёрдость первого согласного — только когда за ним сразу гласная или ь
    soft: VOWELS.includes(f) || !(VOWELS + 'ь').includes(f2) ? null
      : 'чщй'.includes(f) ? true : 'жшц'.includes(f) ? false : SOFTENERS.includes(f2),
    // число звуков = число букв, если в слове нет ь, я/ё/ю/е и оглушения на конце
    sounds: /[ьъяёюе]/.test(word) || DEVOICE.includes(L) || word.length > 5 ? null : word.length,
  };
}));
export const byWord = (w) => ITEMS.find((i) => i.word === w);
