export function countPhrase(n, t, acc = false) {
  if (n === 1) return `${acc && t.g === 'f' ? 'одну' : numWord(1, t.g)} ${t.f[acc ? 1 : 0]}`;
  return `${numWord(n, t.g)} ${plural(n, [t.f[0], t.f[2], t.f[3]])}`;
}
