    // твёрдость первого согласного — только когда за ним сразу гласная или ь
    soft: VOWELS.includes(f) || !(VOWELS + 'ь').includes(f2) ? null
      : 'чщй'.includes(f) ? true : 'жшц'.includes(f) ? false : SOFTENERS.includes(f2),
